"""Mirror every non-null PokeAPI sprites.versions leaf, preserving its source identity.

This module also runs standalone via ``python -`` in the current API container, so
the development preview can be populated before the Docker image is rebuilt.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import os
import random
from collections.abc import Iterator
from io import BytesIO
from pathlib import Path, PurePosixPath
from urllib.parse import urlsplit

import asyncpg  # type: ignore[import-untyped]
import httpx
from PIL import Image, UnidentifiedImageError

logger = logging.getLogger(__name__)
SUPPORTED_FORMATS = {"png": "PNG", "gif": "GIF", "webp": "WEBP"}
type SpriteSourceRow = tuple[str, int, str, str, str, str | None, str | None, str]
CREATE_TABLE = """
CREATE TABLE IF NOT EXISTS version_sprite (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type varchar(12) NOT NULL,
    owner_id integer NOT NULL,
    generation varchar(32) NOT NULL,
    game varchar(64) NOT NULL,
    kind varchar(80) NOT NULL,
    source_url text,
    status varchar(24) NOT NULL,
    format varchar(8),
    checksum varchar(64),
    local_path text,
    byte_size integer,
    width integer,
    height integer,
    frame_count integer,
    error text,
    attempts integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_version_sprite_source UNIQUE
        (owner_type, owner_id, generation, game, kind)
);
CREATE INDEX IF NOT EXISTS ix_version_sprite_owner
    ON version_sprite (owner_type, owner_id);
CREATE INDEX IF NOT EXISTS ix_version_sprite_source_url
    ON version_sprite (source_url);
CREATE INDEX IF NOT EXISTS ix_version_sprite_status
    ON version_sprite (status);
CREATE INDEX IF NOT EXISTS ix_version_sprite_checksum
    ON version_sprite (checksum);
"""


def sprite_leaves(
    value: object, prefix: tuple[str, ...] = ()
) -> Iterator[tuple[tuple[str, ...], str | None]]:
    if isinstance(value, dict):
        for key, child in value.items():
            yield from sprite_leaves(child, (*prefix, str(key)))
    elif value is None or isinstance(value, str):
        yield prefix, value


def sprite_rows(
    owner_type: str, owner_id: int, sprites: dict[str, object]
) -> Iterator[SpriteSourceRow]:
    for path, source_url in sprite_leaves(sprites.get("versions") or {}):
        if len(path) < 3:
            continue
        generation, game, *kind = path
        if source_url is not None and not source_url.startswith(("https://", "http://")):
            continue
        fmt = (
            PurePosixPath(urlsplit(source_url).path).suffix.lower().lstrip(".")
            if source_url
            else None
        )
        yield (
            owner_type,
            owner_id,
            generation,
            game,
            "/".join(kind),
            source_url,
            fmt,
            "pending" if source_url else "null",
        )


async def materialize_source_fields(db: asyncpg.Connection) -> int:
    await db.execute(CREATE_TABLE)
    await db.execute("""
        CREATE TEMP TABLE version_sprite_stage (
            owner_type varchar(12), owner_id integer, generation varchar(32),
            game varchar(64), kind varchar(80), source_url text, format varchar(8),
            status varchar(24)
        ) ON COMMIT PRESERVE ROWS
    """)
    count = 0
    batch: list[SpriteSourceRow] = []
    for owner_type, table in (("pokemon", "pokemon"), ("form", "pokemon_form")):
        async with db.transaction():
            async for row in db.cursor(f"SELECT id, sprites FROM {table} ORDER BY id", prefetch=50):
                sprites = row["sprites"]
                if isinstance(sprites, str):
                    sprites = json.loads(sprites)
                batch.extend(sprite_rows(owner_type, row["id"], sprites or {}))
                if len(batch) >= 20000:
                    await db.copy_records_to_table(
                        "version_sprite_stage",
                        records=batch,
                        columns=[
                            "owner_type",
                            "owner_id",
                            "generation",
                            "game",
                            "kind",
                            "source_url",
                            "format",
                            "status",
                        ],
                    )
                    count += len(batch)
                    batch.clear()
    if batch:
        await db.copy_records_to_table(
            "version_sprite_stage",
            records=batch,
            columns=[
                "owner_type",
                "owner_id",
                "generation",
                "game",
                "kind",
                "source_url",
                "format",
                "status",
            ],
        )
        count += len(batch)
    logger.info("Materialized %s source fields in stage", count)
    await db.execute("""
        INSERT INTO version_sprite
            (owner_type, owner_id, generation, game, kind, source_url, format, status)
        SELECT owner_type, owner_id, generation, game, kind, source_url, format, status
        FROM version_sprite_stage WHERE true
        ON CONFLICT (owner_type, owner_id, generation, game, kind)
        DO UPDATE SET source_url = EXCLUDED.source_url, format = EXCLUDED.format,
            status = EXCLUDED.status, local_path = NULL, checksum = NULL,
            byte_size = NULL, width = NULL, height = NULL, frame_count = NULL,
            error = NULL, attempts = 0, updated_at = now()
        WHERE version_sprite.source_url IS DISTINCT FROM EXCLUDED.source_url
    """)
    await db.execute("DROP TABLE version_sprite_stage")
    return count


def validate_image(data: bytes, extension: str) -> tuple[int, int, int]:
    if not data:
        raise ValueError("empty response")
    with Image.open(BytesIO(data)) as image:
        if image.format != SUPPORTED_FORMATS.get(extension):
            raise ValueError(f"expected {extension}, got {image.format}")
        width, height = image.size
        frames = getattr(image, "n_frames", 1)
        image.verify()
    return width, height, frames


async def download_one(
    client: httpx.AsyncClient, semaphore: asyncio.Semaphore, url: str, fmt: str
) -> tuple[str, bytes | None, tuple[int, int, int] | None, str | None]:
    for attempt in range(3):
        try:
            async with semaphore:
                response = await client.get(url)
            response.raise_for_status()
            data = response.content
            dimensions = validate_image(data, fmt)
            return "downloaded", data, dimensions, None
        except (UnidentifiedImageError, ValueError, OSError) as error:
            if attempt == 2:
                return "corrupt", None, None, str(error)[:500]
            await asyncio.sleep(min(8, 2**attempt + random.random()))
        except (httpx.HTTPError, httpx.TimeoutException) as error:
            if attempt == 2 or (
                isinstance(error, httpx.HTTPStatusError)
                and error.response.status_code not in {429, 500, 502, 503, 504}
            ):
                return "download_failed", None, None, str(error)[:500]
            await asyncio.sleep(min(8, 2**attempt + random.random()))
    return "download_failed", None, None, "retry limit reached"


async def mirror_versions(
    *,
    database_url: str,
    media_root: Path,
    concurrency: int = 12,
    limit: int | None = None,
    owner_id: int | None = None,
) -> dict[str, int]:
    dsn = database_url.replace("postgresql+asyncpg://", "postgresql://")
    db = await asyncpg.connect(dsn, command_timeout=600)
    try:
        if owner_id is None and os.environ.get("VERSION_SPRITE_SKIP_MATERIALIZE") == "1":
            field_count = await db.fetchval("SELECT count(*) FROM version_sprite")
            if not field_count:
                raise RuntimeError("Cannot resume before source fields are materialized")
            logger.info("Resuming from %s existing source fields", field_count)
        else:
            field_count = await materialize_source_fields(db) if owner_id is None else 0
        existing: dict[str, str] = {}
        for row in await db.fetch("""
            SELECT DISTINCT ON (checksum) checksum, local_path
            FROM (
                SELECT checksum, local_path FROM media_asset
                WHERE checksum IS NOT NULL AND local_path IS NOT NULL
                UNION ALL
                SELECT checksum, local_path FROM version_sprite
                WHERE status = 'downloaded' AND checksum IS NOT NULL AND local_path IS NOT NULL
            ) combined ORDER BY checksum, local_path
        """):
            if (media_root / row["local_path"]).is_file():
                existing[row["checksum"]] = row["local_path"]
        pending = await db.fetch(
            """
            SELECT DISTINCT source_url, format FROM version_sprite
            WHERE source_url IS NOT NULL AND status IN ('pending', 'download_failed', 'corrupt')
              AND ($1::integer IS NULL OR source_url IN (
                  SELECT source_url FROM version_sprite
                  WHERE owner_type='pokemon' AND owner_id=$1 AND source_url IS NOT NULL
              ))
            ORDER BY source_url
        """,
            owner_id,
        )
        if limit is not None:
            pending = pending[:limit]
        logger.info(
            "Fields=%s, unique URLs to process=%s, known hashes=%s",
            field_count,
            len(pending),
            len(existing),
        )
        counts = {
            "downloadedUrls": 0,
            "reusedHashes": 0,
            "failedUrls": 0,
            "corruptUrls": 0,
            "newBytes": 0,
        }
        semaphore = asyncio.Semaphore(concurrency)
        async with httpx.AsyncClient(
            timeout=45,
            follow_redirects=True,
            headers={"User-Agent": "pokedex-local/0.1"},
            limits=httpx.Limits(max_connections=concurrency * 2),
        ) as client:
            for start in range(0, len(pending), concurrency * 4):
                batch = pending[start : start + concurrency * 4]
                results = await asyncio.gather(
                    *(
                        download_one(client, semaphore, row["source_url"], row["format"])
                        for row in batch
                    )
                )
                updates = []
                for row, (status, data, dimensions, error) in zip(batch, results, strict=True):
                    checksum = local_path = byte_size = width = height = frame_count = None
                    if status == "downloaded" and data is not None and dimensions is not None:
                        checksum = hashlib.sha256(data).hexdigest()
                        local_path = existing.get(checksum)
                        if local_path is None:
                            relative = (
                                Path("version-sprites")
                                / checksum[:2]
                                / f"{checksum}.{row['format']}"
                            )
                            destination = media_root / relative
                            destination.parent.mkdir(parents=True, exist_ok=True)
                            if not destination.is_file():
                                temporary = destination.with_name(
                                    destination.name + f".{os.getpid()}.part"
                                )
                                temporary.write_bytes(data)
                                os.replace(temporary, destination)
                                counts["newBytes"] += len(data)
                            local_path = relative.as_posix()
                            existing[checksum] = local_path
                        else:
                            counts["reusedHashes"] += 1
                        byte_size = len(data)
                        width, height, frame_count = dimensions
                        counts["downloadedUrls"] += 1
                    elif status == "corrupt":
                        counts["corruptUrls"] += 1
                    else:
                        counts["failedUrls"] += 1
                    updates.append(
                        (
                            status,
                            checksum,
                            local_path,
                            byte_size,
                            width,
                            height,
                            frame_count,
                            error,
                            row["source_url"],
                        )
                    )
                await db.executemany(
                    """
                    UPDATE version_sprite SET status=$1, checksum=$2, local_path=$3,
                        byte_size=$4, width=$5, height=$6, frame_count=$7,
                        error=$8, attempts=attempts+1, updated_at=now()
                    WHERE source_url=$9 AND status IN ('pending', 'download_failed', 'corrupt')
                """,
                    updates,
                )
                if start % (concurrency * 4 * 20) == 0 or start + len(batch) == len(pending):
                    logger.info(
                        "Processed %s/%s URLs: %s", start + len(batch), len(pending), counts
                    )
        return {"sourceFields": field_count, "uniqueUrlsProcessed": len(pending), **counts}
    finally:
        await db.close()


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)
    limit = os.environ.get("VERSION_SPRITE_LIMIT")
    owner_id = os.environ.get("VERSION_SPRITE_OWNER_ID")
    result = asyncio.run(
        mirror_versions(
            database_url=os.environ["DATABASE_URL"],
            media_root=Path(os.environ.get("MEDIA_ROOT", "/app/media")),
            concurrency=int(os.environ.get("VERSION_SPRITE_CONCURRENCY", "12")),
            limit=int(limit) if limit else None,
            owner_id=int(owner_id) if owner_id else None,
        )
    )
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
